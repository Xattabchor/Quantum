package code.utils;

/**
 * Кадровый кэш системного времени.
 *
 * {@code System.currentTimeMillis()} - нативный вызов, и на ARM9 он стоит
 * заметно дороже арифметики вокруг него. В оригинале его вызывали по разу на
 * каждый спрайт (Sprite.updateFrame), на каждую анимированную текстуру
 * (Texture.updateAnimation) и ещё несколько раз на NPC и игрока - то есть
 * десятки раз за кадр, хотя все эти таймеры работают с точностью до кадра.
 *
 * Теперь время читается один раз за кадр в {@link QFPS#frame()}, а все
 * покадровые таймеры анимации и отображения берут его отсюда. Расхождение с
 * реальным временем не превышает длительности кадра и на скорость анимации не
 * влияет. Записи таймеров (например {@code lastAttack = System.currentTimeMillis()}
 * при выстреле) остаются на настоящем времени: они событийные и редкие.
 *
 * Места, где важна настоящая точность (ограничитель кадров в GameScreen,
 * измерение времени загрузки), кадровый кэш НЕ используют.
 */
public final class FrameClock {

    /** Время начала текущего кадра в миллисекундах. */
    public static long now = 0L;

    /** Время первого кадра: отсчёт для {@link #elapsed()}. */
    public static long base = 0L;

    private FrameClock() {
    }

    /** Вызывается один раз за кадр из {@link QFPS#frame()}. */
    public static void tick() {
        long t = System.currentTimeMillis();
        if(base == 0L) base = t;
        now = t;
    }

    /**
     * Текущее время; если кадр ещё не начинался (например, анимация считается
     * до первого QFPS.frame()), возвращается настоящее время.
     */
    public static final long time() {
        return now != 0L ? now : System.currentTimeMillis();
    }

    /**
     * Сколько миллисекунд прошло с первого кадра. Помещается в int, поэтому
     * остаток от деления на период анимации можно брать 32-битным делением:
     * 64-битное деление на ARM9 - библиотечная подпрограмма.
     *
     * Фаза анимации при этом сдвигается на постоянную величину (момент
     * запуска), скорость и взаимная синхронность анимаций не меняются.
     */
    public static int elapsed() {
        long d = now - base;
        if(d < 0L || d > 2147483647L) {
            // аномалия (перевод часов или сутки непрерывной работы) -
            // начинаем отсчёт заново
            base = now;
            return 0;
        }
        return (int) d;
    }
}
